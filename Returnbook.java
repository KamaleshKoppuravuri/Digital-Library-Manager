   public void Returnbook_Load()
    {
        int a;
        try {
            pst = con.prepareStatement("select id,memberid,membername,bookid,bookname,returndate,elaps,fine from returnbook");
            rs = pst.executeQuery();
            ResultSetMetaData rsd = rs.getMetaData();
            a = rsd.getColumnCount();
            DefaultTableModel d =  (DefaultTableModel)jTable1.getModel();
            d.setRowCount(0);
            while(rs.next())
            {
                Vector v2 = new Vector();
                for(int i=1;i<=a;i++)
                {
                    v2.add(rs.getString("id"));
                    v2.add(rs.getString("memberid"));
                    v2.add(rs.getString("membername"));
                    v2.add(rs.getString("bookid"));
                    v2.add(rs.getString("bookname"));
                    v2.add(rs.getString("returndate"));
                    v2.add(rs.getString("elaps"));
                    v2.add(rs.getString("fine"));
                }
                d.addRow(v2);
            }   
        } catch (SQLException ex) {
            Logger.getLogger(Member.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    
    

