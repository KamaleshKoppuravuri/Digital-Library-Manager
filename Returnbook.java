    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        
        String sql = "select membername,bookname,returndate,CAST(julianday('now') - julianday(returndate) As Integer )  as elap  from lendbook where memberid=? and bookid=?";
        try{
            pst=con.prepareStatement(sql);
            pst.setString(1, mid.getText());
            pst.setString(2, bid.getText());
            rs=pst.executeQuery();
            if(rs.next()){
                String a1 = rs.getString("membername");
                txtmname.setText(a1);
                String a2 = rs.getString("bookname");
                txtbname.setText(a2);
                String date = rs.getString("returndate");  
                rdate.setText(date);
                String elp = rs.getString("elap");
                int elaped = Integer.parseInt(elp);     
                      if(elaped > 0)
                      {                 
                          day.setText(elp);  
                          int fine = elaped * 5; 
                          txtfine.setText(String.valueOf(fine));      
                      }
                      else
                      {
                          day.setText("0");
                          txtfine.setText("0"); 
                      }
                      rs.close();
                      pst.close();
            }
            else{
                JOptionPane.showMessageDialog(null, "Book is not Issued with this Member");
            }
        }catch(Exception e){
            JOptionPane.showMessageDialog(null, e);
        }
    }//GEN-LAST:event_jButton2ActionPerformed

